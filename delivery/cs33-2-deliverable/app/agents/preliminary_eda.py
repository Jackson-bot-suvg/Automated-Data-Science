"""Preliminary EDA node.

Reads raw CSV files and uses the lower-level profiler to generate precise
context JSON, preparing structured dataset profile data for the LLM Planner.
"""

from __future__ import annotations

import json
import os
from pathlib import Path
from typing import Any

import matplotlib
matplotlib.use("Agg")  # Non-interactive backend
import matplotlib.pyplot as plt
import pandas as pd
import seaborn as sns

from app.schemas.state_schema import GraphState
from app.tools.profiler import profile_dataset
from app.tools import file_tools
from app.utils.target_scope import get_target_columns

# ──────────────────────────────────────────────
# Reserved artifact key
# ──────────────────────────────────────────────
_EDA_REPORT_KEY = "preliminary_eda_report"


def run_preliminary_eda(state: GraphState) -> dict:
    """Execute the Preliminary EDA phase and return a partial state update.

    The main logic now uses ``profile_dataset`` to extract a dense JSON
    feature profile, stores it in ``data_state.eda_findings``, and passes it
    downstream for the next Planner step.
    """
    train_path = state.data_state.current_train_path
    test_path = state.data_state.current_test_path

    # 1. Validate input paths
    if not train_path or not Path(train_path).exists():
        return _error_envelope(
            phase="preliminary_eda",
            error_type="artifact_missing",
            message=f"Training dataset file does not exist or the path is empty: '{train_path}'",
        )

    # 2. Read data
    df_train = pd.read_csv(train_path)
    df_test = pd.read_csv(test_path) if test_path and Path(test_path).exists() else None

    # 3. Read target columns from target_spec instead of hard-coding them
    target_cols = get_target_columns(state)

    # Extract a compact statistical profile
    eda_findings_json = profile_dataset(df_train, target_cols=target_cols)

    # 4. Keep a minimal schema summary for downstream compatibility
    schema_summary = {"columns": list(df_train.columns)}

    # 5. Ensure output directories exist
    report_path = str(state.artifacts.get(_EDA_REPORT_KEY) or "artifacts/eda/preliminary_eda.md")
    os.makedirs(Path(report_path).parent, exist_ok=True)

    # 6. Generate basic distribution charts for human inspection
    new_figures: list[str] = []
    # Missing values
    missing = df_train.isnull().sum()
    missing = missing[missing > 0]
    if not missing.empty:
        fig, ax = plt.subplots(figsize=(8, 4))
        sns.barplot(x=missing.index.tolist(), y=missing.values.tolist(), ax=ax, palette="viridis")
        ax.set_title("Missing Values Training Set")
        plt.tight_layout()
        path = file_tools.figure_path(
            workspace_root=state.runtime_state.workspace_root,
            artifact_root=state.runtime_state.artifact_root,
            filename="eda_missingness.png",
        )
        fig.savefig(path, dpi=100)
        plt.close(fig)
        new_figures.append(path)

    # 7. Write the structured profile to Markdown for humans
    _write_eda_report(df_train, eda_findings_json, new_figures, report_path)

    existing_figures: list[str] = list(state.artifacts.get("figures", []))

    # 8. Push the extracted profile into downstream Planner state
    return {
        "data_state": {
            **state.data_state.model_dump(),
            "schema_summary": schema_summary,
            "eda_findings": eda_findings_json,  # Passed downstream to the LLM Planner as dict/JSON
        },
        "artifacts": {
            **state.artifacts,
            "preliminary_eda_report": report_path,
            "figures": existing_figures + new_figures,
        },
        "current_phase": "preliminary_eda",
        "phase_history": ["preliminary_eda"],  
    }


# ──────────────────────────────────────────────
# Internal helper functions
# ──────────────────────────────────────────────

def _write_eda_report(
    df: pd.DataFrame,
    profile_json: dict,
    figures: list[str],
    report_path: str,
) -> None:
    """Render the extracted EDA JSON profile into a simple Markdown report."""
    lines: list[str] = [
        "# Preliminary EDA Feature Profile Report\n\n",
        "This report is generated by the low-level profiler and will be passed in full to the LLM Planner for tool planning.\n\n",
        "## Dataset Overview\n",
        f"- Rows: {profile_json['dataset_shape']['rows']}\n",
        f"- Columns: {profile_json['dataset_shape']['columns']}\n\n",
        "## Core Feature Profile (Context for the LLM)\n\n"
        "```json\n" + json.dumps(profile_json, ensure_ascii=False, indent=2) + "\n```\n\n"
    ]

    if figures:
        lines.append("\n## Generated Figures\n\n")
        for fig_path in figures:
            lines.append(f"- `{fig_path}`\n")

    with open(report_path, "w", encoding="utf-8") as fh:
        fh.writelines(lines)


def _error_envelope(phase: str, error_type: str, message: str, details: dict | None = None) -> dict:
    error_str = f"[{phase}] {error_type}: {message}"
    return {
        "runtime_state": {
            "interrupted": True,
        },
        "review_state": {
            "fatal_errors": [error_str]
        },
    }
